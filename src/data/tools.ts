export function getToolById(id: string): Tool | undefined {
  return tools.find((t) => t.id === id)
}

export function getToolsByCategory(categoryId: string): Tool[] {
  return tools.filter((t) => t.category === categoryId)
}

export function getPopularTools(): Tool[] {
  return tools.filter((t) => t.popular)
}

export function getTrendingTools(): Tool[] {
  return tools.filter((t) => t.trending)
}

export function getNewTools(): Tool[] {
  return tools.filter((t) => t.new)
}

export function getRelatedTools(toolId: string): Tool[] {
  const tool = getToolById(toolId)
  if (!tool) return []
  return tools.filter((t) => tool.relatedTools.includes(t.id))
}

export function searchTools(query: string): Tool[] {
  const q = query.toLowerCase()
  return tools.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.categoryLabel.toLowerCase().includes(q) ||
      t.benefits.some((b) => b.toLowerCase().includes(q))
  )
}
